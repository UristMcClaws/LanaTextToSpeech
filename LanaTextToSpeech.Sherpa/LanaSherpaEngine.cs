using NAudio.CoreAudioApi;
using NAudio.Wave;
using SherpaOnnx;

namespace LanaTextToSpeech.Sherpa;

public class LanaSherpaEngine
{
    private int deviceIndex;
    private string directory;
    private OfflineTtsConfig config;

    public LanaSherpaEngine(string modelKey, string directory = null, int deviceIndex = 0)
    {
        this.directory = directory ?? Directory.GetCurrentDirectory();
        this.deviceIndex = deviceIndex;

        LoadModel(modelKey);
    }

    public OfflineTtsGeneratedAudio GenerateAudio(string text, int voice = 0)
    {
        // 2. Initialize the TTS engine
        using (OfflineTts tts = new OfflineTts(config))
        {
            // 3. Generate the audio (Text, Speaker ID, Speed)
            var generatedAudio = tts.Generate(text, 1.0f, voice);

            return generatedAudio;

            //// 4. Save the generated byte array directly to a file
            //generatedAudio.SaveToWaveFile("output.wav");

            // 4. Play the generated audio
            PlayAudio(generatedAudio);
        }
    }

    public void SaveAudioToFile(OfflineTtsGeneratedAudio audioData, string filePath)
    {
        audioData.SaveToWaveFile(filePath);
    }

    public void PlayAudio(OfflineTtsGeneratedAudio audioData)
    {
        var enumerator = new MMDeviceEnumerator();
        var devices = enumerator.EnumerateAudioEndPoints(DataFlow.Render, DeviceState.Active);

        float[] audioSamples = audioData.Samples;
        int sampleRate = audioData.SampleRate;

        var sampleProvider = new FloatArraySampleProvider(audioSamples, sampleRate);

        using (var player = new WasapiPlayerBuilder().WithDevice(devices[deviceIndex]).Build())
        {
            player.Init(sampleProvider.ToWaveProvider());
            player.Play();

            while (player.PlaybackState == PlaybackState.Playing)
            {
                Thread.Sleep(100);
            }
        }
    }

    private void LoadModel(string modelKey, string tokensFile = "tokens.txt", string dataDir = "espeak-ng-data")
    {
        string directory = Directory.GetCurrentDirectory();
        string modelDirectory = Path.Join(directory, "models", modelKey);
        if (!Directory.Exists(modelDirectory))
        {
            throw new DirectoryNotFoundException($"Model directory '{modelDirectory}' not found!");
        }
        string modelFilePath = Path.Join(modelDirectory, $"{modelKey}.onnx");
        string tokensFilePath = Path.Join(modelDirectory, tokensFile);
        string dataDirPath = Path.Join(modelDirectory, dataDir);
        bool modelFileExists = File.Exists(modelFilePath);
        bool tokensFileExists = File.Exists(tokensFilePath);
        bool dataDirExists = Directory.Exists(dataDirPath);
        if (!File.Exists(modelFilePath) || !File.Exists(tokensFilePath) || !Directory.Exists(dataDirPath))
        {
            throw new FileNotFoundException("One or more required model files are missing.");
        }
        else
        {
            config.Model.Vits.Model = modelFilePath;
            config.Model.Vits.Tokens = tokensFilePath;
            config.Model.Vits.DataDir = dataDirPath;
        }
    }
}